"""A workflow's object model, drawn from its declarations: never hand-written (bd fix-qjne.37.2).

Each context's ``class Context`` declares what it inherits (``inherits``) and what contains its records (``parents``);
each command's ``@descends_to`` declares the context it enters. :func:`object_model` reads them all into one
:class:`ObjectModel` (for a test or a coding agent) and :func:`render_object_model` draws it as plain markdown: the
containment tree under the global commands, then one table row per context. ``fastworkflow command preview`` writes it
beside the planning command previews (``<out>/_object_models/<workflow>.md``) and ``--check`` compares it.

There is no root declaration: the root record is whatever the workflow sets as ``workflow.root`` at run time (usually
its startup command), so the view names the top-level contexts (no ``parents``) and says so.
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field

#: The folder of ``<out>`` the object models are written to, one ``<workflow folder name>.md`` per workflow.
OBJECT_MODELS_FOLDER = "_object_models"
MARKER = "<!-- Generated by `fastworkflow command preview` from the declarations of {source}. Do not edit: regenerate. -->"


@dataclass(frozen=True)
class ObjectModel:
    """Every context of a workflow once, with what it declares and the commands that enter it."""

    workflow: str
    contexts: tuple[str, ...]
    inherits: dict[str, tuple[str, ...]] = field(default_factory=dict)      # declared, in order
    parents: dict[str, tuple[str, ...]] = field(default_factory=dict)       # declared, in order
    entered_by: dict[str, tuple[str, ...]] = field(default_factory=dict)    # context -> commands, sorted
    never_entered: tuple[str, ...] = ()                                      # occupiable = False

    @property
    def top_level(self) -> tuple[str, ...]:
        """The contexts with no ``parents``, enclosed only by the global commands (mixins excluded)."""
        return tuple(name for name in self.contexts if name not in self.parents and name not in self.never_entered)

    def children(self, context: str) -> tuple[str, ...]:
        """The contexts that name *context* among their ``parents``, sorted."""
        return tuple(name for name in self.contexts if context in self.parents.get(name, ()))


def object_model(workflow_folder: str) -> ObjectModel:
    """Read the object model of *workflow_folder*: the context folders (``context_folders``), the declarations of
    their ``class Context`` (``inherits``, ``parents``, ``occupiable``) and every command's ``@descends_to``. Raises
    ``CommandContextModelValidationError`` when the declarations do not read."""
    import fastworkflow
    from fastworkflow.core.command_context_model import CommandContextModel, context_folders
    from fastworkflow.core.command_declarations import declared_descend
    from fastworkflow.core.command_routing import RoutingRegistry

    folder = os.path.abspath(workflow_folder)
    contexts = tuple(sorted(context_folders(folder)))
    routing = RoutingRegistry.get_definition(folder)
    entered: dict[str, set[str]] = {}
    for command in sorted({name for names in routing.contexts.values() for name in names}):
        try:
            generator = routing.get_command_class(command, fastworkflow.ModuleType.RESPONSE_GENERATION_INFERENCE)
        except Exception:  # noqa: BLE001 - a command that does not load is its own load problem
            continue
        if (target := declared_descend(generator)) is not None:
            entered.setdefault(target, set()).add(command)
    never_entered = []
    for name in contexts:
        try:
            context_class = routing.context_model.get_context_class(name, fastworkflow.ModuleType.CONTEXT_CLASS)
        except Exception:  # noqa: BLE001 - a context class that does not load is its own load problem
            continue
        if getattr(context_class, "occupiable", None) is False:
            never_entered.append(name)
    return ObjectModel(
        workflow=os.path.basename(folder),
        contexts=contexts,
        inherits={name: tuple(bases) for name, bases in CommandContextModel.declared_bases(folder).items()},
        parents={name: tuple(parents) for name, parents in CommandContextModel.declared_parents(folder).items()},
        entered_by={name: tuple(sorted(commands)) for name, commands in sorted(entered.items())},
        never_entered=tuple(never_entered),
    )


def _names(names: tuple[str, ...]) -> str:
    return ", ".join(f"`{name}`" for name in names)


def _tree(model: ObjectModel) -> list[str]:
    """The containment tree: each top-level context under the global commands, each context under every parent it
    names. A context is drawn in full once; where it shows again (a second parent, or a record nested in its own
    kind) it is named with "(see above)"."""
    lines = ["- global commands"]
    drawn: set[str] = set()

    def draw(name: str, depth: int) -> None:
        entered = model.entered_by.get(name)
        note = f" (entered by {_names(entered)})" if entered else ""
        if name in drawn:
            lines.append(f"{'  ' * depth}- {name} (see above)")
            return
        drawn.add(name)
        lines.append(f"{'  ' * depth}- {name}{note}")
        for child in model.children(name):
            draw(child, depth + 1)

    for name in model.top_level:
        draw(name, 1)
    # A context whose parents never lead to a top-level context (records nested only in their own kind)
    for name in model.contexts:
        if name not in drawn and name not in model.never_entered:
            draw(name, 1)
    return lines


def render_object_model(workflow_folder: str) -> str:
    """The object model of *workflow_folder* as markdown (deterministic: contexts and commands sorted, declarations
    in their declared order)."""
    model = object_model(workflow_folder)
    out = [MARKER.format(source=model.workflow), "", f"# Object model: {model.workflow}", "",
           "Drawn from each context's `class Context` in `_commands/<Context>/_<Context>.py` (`inherits`, `parents`, "
           "`occupiable`) and each command's `@descends_to`. No file declares the root: the root record is the one "
           "the workflow sets as `workflow.root` at run time, usually in its startup command.", ""]
    if not model.contexts:
        out += ["No contexts: every command is a global command.", ""]
        return "\n".join(out)
    out += ["## Containment", "", *_tree(model), ""]
    if model.never_entered:
        out += [f"Never entered (`occupiable = False`, inherited only): {_names(model.never_entered)}", ""]
    out += ["## Contexts", "", "| Context | Inherits | Parents | Entered by |", "|---|---|---|---|"]
    for name in model.contexts:
        parents = (_names(model.parents[name]) if name in model.parents
                   else "never entered" if name in model.never_entered else "top level")
        out.append(f"| `{name}` | {_names(model.inherits.get(name, ())) or '-'} | {parents} | "
                   f"{_names(model.entered_by.get(name, ())) or '-'} |")
    out.append("")
    return "\n".join(out)


def object_model_path(workflow_folder: str, out_dir: str) -> str:
    """``<out>/_object_models/<workflow folder name>.md``: one file per workflow, so workflows that share a previews
    folder (the shipped examples) each have their own."""
    return os.path.join(out_dir, OBJECT_MODELS_FOLDER, f"{os.path.basename(os.path.abspath(workflow_folder))}.md")


def check_object_model(workflow_folder: str, out_dir: str) -> list[str]:
    """``["missing: ..."]`` or ``["stale: ..."]`` when the written object model is not a fresh render; else [].

    There is no "extra" object model: each workflow owns exactly one file, named after its folder, and workflows
    that share *out_dir* (the shipped examples, or any two given the same ``--out``) each write their own, so no
    workflow can tell another's file from a leftover."""
    path = object_model_path(workflow_folder, out_dir)
    name = os.path.relpath(path, out_dir).replace(os.sep, "/")
    if not os.path.isfile(path):
        return [f"missing: {name}"]
    with open(path, encoding="utf-8", newline="") as handle:
        return [] if handle.read() == render_object_model(workflow_folder) else [f"stale: {name}"]


def write_object_model(workflow_folder: str, out_dir: str) -> bool:
    """Write the object model of *workflow_folder* under *out_dir*; True when the file changed."""
    path = object_model_path(workflow_folder, out_dir)
    text = render_object_model(workflow_folder)
    if os.path.isfile(path):
        with open(path, encoding="utf-8", newline="") as handle:
            if handle.read() == text:
                return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    return True


__all__ = ["OBJECT_MODELS_FOLDER", "ObjectModel", "check_object_model", "object_model", "object_model_path",
           "render_object_model", "write_object_model"]
